export const translations = { de: german, fr: french, es: spanish, pt: portuguese, it: italian, nl: dutch, pl: polish };
const table = translations[language] ?? {};
export const t = text => table[text] ?? text;
export const dieType = sides => `${t('D')}${sides}`;

// Name from the die types in dice order, e.g. "3×D6 · D20".
export function diceName(sides) {
  const counts = new Map();
  for (const s of sides) counts.set(s, (counts.get(s) ?? 0) + 1);
  return [...counts].map(([s, n]) => n > 1 ? `${n}×${dieType(s)}` : dieType(s)).join(' · ');
}

export function localize(doc) {
  doc.documentElement.lang = language;
  if (language === 'en') return;
  doc.querySelector('link[rel="manifest"]').href = `manifest.${language}.webmanifest`;
  for (const meta of doc.querySelectorAll('meta[name="description"]')) meta.content = t(meta.content);
  const walker = doc.createTreeWalker(doc.body, 4); // SHOW_TEXT; leaves icons and nested labels intact.
  while (walker.nextNode()) {
    const node = walker.currentNode;
    const key = node.textContent.trim();
    if (Object.hasOwn(table, key)) node.textContent = node.textContent.replace(key, table[key]);
  }
  for (const el of doc.querySelectorAll('[aria-label]')) el.setAttribute('aria-label', t(el.getAttribute('aria-label')));
}
