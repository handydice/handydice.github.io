export const LANGUAGE_KEY = 'handydice-language';

export const LANGUAGES = ['en', 'de', 'fr', 'es', 'pt', 'it', 'nl', 'pl'];

// A manual choice wins; Auto uses the first supported browser preference, otherwise English.
export function chooseLanguage(languages, preference = 'auto') {
  if (LANGUAGES.includes(preference)) return preference;
  return languages.map(lang => lang.toLowerCase().split('-')[0])
    .find(lang => LANGUAGES.includes(lang)) ?? 'en';
}
const stored = globalThis.window?.localStorage.getItem(LANGUAGE_KEY);
export const languagePreference = LANGUAGES.includes(stored) ? stored : 'auto';
export const language = chooseLanguage(
  globalThis.navigator?.languages ?? [globalThis.navigator?.language ?? 'en'],
  languagePreference,
);

